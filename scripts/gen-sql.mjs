// Embeds database/*.sql into a JS module so the Netlify bundler ships them with the function.
// Run `npm run gen-sql` after editing any .sql file (and bump SCHEMA_VERSION in netlify/functions/lib/sql.mjs's generator below if migrate.sql changed).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const rd = f => readFileSync(join(root, 'database', f), 'utf8');
const SCHEMA_VERSION = '6';   // bump whenever database/migrate.sql changes: every install then upgrades itself once, automatically
const out = `// GENERATED by scripts/gen-sql.mjs from database/*.sql. Do not edit by hand.
export const SCHEMA_VERSION = ${JSON.stringify(SCHEMA_VERSION)};
export const SCHEMA_SQL = ${JSON.stringify(rd('schema.sql'))};
export const MIGRATE_SQL = ${JSON.stringify(rd('migrate.sql'))};
export const SEED_SQL = ${JSON.stringify(rd('shop_seed.sql'))};
`;
writeFileSync(join(root, 'netlify/functions/lib/sql.mjs'), out);
console.log('wrote netlify/functions/lib/sql.mjs');
